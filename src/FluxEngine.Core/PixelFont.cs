        ['Z'] = new[] { "#####", "   # ", "  #  ", " #   ", "#    ", "#####" },
        ['0'] = new[] { ".###.", "#...#", "#.#.#", "#.#.#", "#...#", ".###." },
        ['1'] = new[] { "  #  ", " ##  ", "  #  ", "  #  ", "  #  ", "#####" },
        ['2'] = new[] { "#### ", "   # ", "   # ", " ####", "#    ", "#####" },
        ['3'] = new[] { "#### ", "   # ", " .## ", "   # ", "   # ", "#### " },
        ['4'] = new[] { "#..# ", "#..# ", "#..# ", "#### ", "   # ", "   # " },
        ['5'] = new[] { "#####", "#....", "#### ", "   # ", "   # ", "#### " },
