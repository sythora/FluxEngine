        [')'] = new[] { " #.  ", "   # ", "   # ", "   # ", "   # ", " #.  " },
        ['_'] = new[] { "     ", "     ", "     ", "     ", "     ", "#####" },
    };

    private readonly float _pixelSize;
    private readonly Color _color;

    public PixelFont(float pixelSize = 3f, Color? color = null)
    {
        _pixelSize = pixelSize;
        _color = color ?? Color.White;
    }

    public void Draw(Renderer renderer, string text, Vector2 position, float scale = 1f)
    {
        var x = position.X;
        var pixelSize = _pixelSize * scale;

        foreach (var c in text)
        {
            if (!Glyphs.TryGetValue(c, out var rows))
            {
                x += 6 * pixelSize;
                continue;
            }

            for (var row = 0; row < rows.Length; row++)
            {
                var line = rows[row];
                for (var col = 0; col < line.Length; col++)
                {
                    if (line[col] == '#')
                    {
                        var px = x + col * pixelSize;
                        var py = position.Y + row * pixelSize;
                        renderer.DrawRectangle(
                            new Rectangle(px, py, pixelSize, pixelSize),
                            _color);
                    }
                }
            }

            x += 6 * pixelSize;
        }
    }

    public float MeasureWidth(string text, float scale = 1f)
        => text.Length * 6 * _pixelSize * scale;
}
