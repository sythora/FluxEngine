        ['R'] = new[] { "#### ", "#...#", "#### ", "#.#..", "#..#.", "#...#" },
        ['S'] = new[] { ".###.", "#....", ".###.", "....#", "#...#", ".###." },
        ['T'] = new[] { "#####", " #.# ", " #.# ", " #.# ", " #.# ", " #.# " },
        ['U'] = new[] { "#...#", "#...#", "#...#", "#...#", "#...#", ".###." },
