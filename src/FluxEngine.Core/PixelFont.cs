using FluxEngine.Graphics;
using FluxEngine.Mathematics;

// Bitmap font rendered with rectangles. Each character is a 5x6 grid of
// pixels. No external font files required.
public sealed class PixelFont
{
    // 5 columns x 6 rows per character. '#' is a pixel, ' ' is empty.
    private static readonly Dictionary<char, string[]> Glyphs = new()
    {
        ['A'] = new[] { ".###.", "#...#", "#...#", "#####", "#...#", "#...#" },
        ['B'] = new[] { "#### ", "#...#", "#### ", "#...#", "#...#", "#### " },
        ['C'] = new[] { ".###.", "#....", "#....", "#....", "#....", ".###." },
        ['D'] = new[] { "#### ", "#...#", "#...#", "#...#", "#...#", "#### " },
        ['E'] = new[] { "#####", "#....", "#### ", "#....", "#....", "#####" },
