        ['J'] = new[] { "#####", "   # ", "   # ", "   # ", "#..# ", ".##."  },
        ['K'] = new[] { "#...#", "#..#.", "#.#..", "##...", "#..#.", "#...#" },
        ['L'] = new[] { "#....", "#....", "#....", "#....", "#....", "#####" },
        ['M'] = new[] { "#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#" },
